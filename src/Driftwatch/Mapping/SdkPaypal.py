"""Derive a Surface Map from PayPal's generated Python Server SDK.

PayPal's official SDK is generated by APIMATIC rather than using Stripe's service-class
layout. Controller methods contain the API path in ``.path(...)`` and the HTTP verb in
``.http_method(HttpMethodEnum.POST)``. Keeping this adapter separate makes the provider
specific parsing explicit while preserving the shared SurfaceMap contract.
"""

from __future__ import annotations

import re
from pathlib import Path

from Driftwatch.Mapping.Model import PROVENANCE_CONFIDENCE, SurfaceMap, SurfaceMapEntry
from Driftwatch.Surfaces import op_ref

_METHOD_RE = re.compile(
    r"(?ms)^\s*def\s+(?P<name>[a-zA-Z_]\w*)\s*\((?P<params>.*?)\):"
    r"(?P<body>.*?)(?=^\s*def\s|\Z)"
)
_PATH_RE = re.compile(r'\.path\(\s*["\'](?P<path>/[^"\']+)["\']\s*\)')
_VERB_RE = re.compile(r"\.http_method\(\s*HttpMethodEnum\.(?P<verb>[A-Z]+)\s*\)")
_OPTION_RE = re.compile(r"options\.get\(\s*[\"'](?P<name>[^\"']+)[\"']")


def derive_paypal_python(
    sdk_root: Path, provider: str = "paypal", sdk_version: str = "unknown"
) -> SurfaceMap:
    """Build bindings from generated PayPal controller source.

    The adapter intentionally only accepts methods containing both a literal path and an
    HTTP verb. A controller method that does not expose both is skipped rather than guessed.
    """
    package = sdk_root / "paypalserversdk"
    if not package.is_dir():
        raise FileNotFoundError(f"expected a 'paypalserversdk' package under {sdk_root}")

    result = SurfaceMap(
        provider=provider,
        language="python",
        sdk_package="paypal-server-sdk",
        sdk_version=sdk_version,
    )
    confidence = PROVENANCE_CONFIDENCE["sdk_source_derived"]
    seen: set[tuple[str, str]] = set()

    for path in sorted(package.glob("controllers/*_controller.py")):
        source = path.read_text(encoding="utf-8")
        module = f"paypalserversdk.controllers.{path.stem}"
        class_name = _controller_name(path.stem)
        for match in _METHOD_RE.finditer(source):
            body = match.group("body")
            path_match = _PATH_RE.search(body)
            verb_match = _VERB_RE.search(body)
            if path_match is None or verb_match is None:
                continue
            surface = op_ref(provider, verb_match.group("verb"), path_match.group("path"))
            symbol = f"py:{module}.{class_name}.{match.group('name')}"
            if (surface, symbol) not in seen:
                result.add(
                    SurfaceMapEntry(
                        surface_ref=surface,
                        symbol_ref=symbol,
                        confidence=confidence,
                        source_locator=(
                            f"{path}:{source[:match.start()].count(chr(10)) + 1}"
                        ),
                    )
                )
                seen.add((surface, symbol))

            params = result.op_params.setdefault(surface, [])
            for name in _OPTION_RE.findall(body):
                if name not in params:
                    params.append(name)

    return result


def _controller_name(stem: str) -> str:
    """Turn ``orders_controller`` into ``OrdersController``."""
    return "".join(part.capitalize() for part in stem.split("_"))
